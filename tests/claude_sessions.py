def stamp(seconds: float) -> str:
    """A timestamp as Claude Code writes one: milliseconds and `Z`."""
    return (T0 + timedelta(seconds=seconds)).strftime("%Y-%m-%dT%H:%M:%S.000Z")


def at(seconds: float) -> str:
    """The same instant as the record spells it."""
    return (T0 + timedelta(seconds=seconds)).strftime("%Y-%m-%dT%H:%M:%SZ")


def _base(kind: str, seconds: float, n: int, session: str = SESSION, **more: Any) -> dict[str, Any]:
    entry: dict[str, Any] = {
        "parentUuid": None if n == 1 else f"uuid-{n - 1}",
        "isSidechain": False,
        "userType": "external",
        "cwd": CWD,
        "sessionId": session,
        "version": "2.0.0",
        "gitBranch": "main",
        "type": kind,
        "uuid": f"uuid-{n}",
        "timestamp": stamp(seconds),
    }
    entry.update(more)
    return entry


def user(seconds: float, n: int, content: Any, **more: Any) -> dict[str, Any]:
    return _base("user", seconds, n, message={"role": "user", "content": content}, **more)


def assistant(
    seconds: float, n: int, blocks: list[dict[str, Any]], message_id: str, **more: Any
) -> dict[str, Any]:
    model = more.pop("model", MODEL)
    message = {"id": message_id, "type": "message", "role": "assistant", "model": model, "content": blocks}
    return _base("assistant", seconds, n, message=message, requestId=f"req-{n}", **more)


def text(words: str) -> dict[str, Any]:
    return {"type": "text", "text": words}


