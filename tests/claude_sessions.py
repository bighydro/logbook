def second_session() -> list[Any]:
    """Another, shorter session of the same project, a day later."""
    day = 86400
    return [
        user(day, 1, "Add the moon phase to the planner, please.", session=SECOND),
        assistant(day + 4, 2, [text("Added the moon phase.")], "msg-9", session=SECOND),
    ]


def write(file: Path, lines: list[Any]) -> Path:
    file.parent.mkdir(parents=True, exist_ok=True)
    body = "".join(
        (line if isinstance(line, str) else json.dumps(line, ensure_ascii=False)) + "\n" for line in lines
    )
    file.write_bytes(body.encode("utf-8"))
    return file


def projects(folder: Path) -> Path:
    """`~/.claude/projects/` with the one project, its two sessions and a subagent's own file."""
    project = folder / PROJECT
    write(project / f"{SESSION}.jsonl", entries())
    write(project / f"{SECOND}.jsonl", second_session())
    write(
        project / "agent-0a1b2c3d.jsonl",
        [user(100, 1, f"Subagent prompt. {SIDECHAIN}", isSidechain=True, agentId="0a1b2c3d")],
    )
    return folder
