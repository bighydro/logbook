"""flight/v1 (RFC 0013): one flight the owner was on, seen by up to three producers.

This module is the one mapping every producer shares (ADR 0017). `build` makes a draft from the
fields a producer has; `parse_declaration` reads the owner's sentence (`logbook add flight "…"`);
the `flighty` adapter and `infer` (`logbook infer flights`) call `build` with what they read. `key`
is the flight's identity, `(date, carrier, number)`; `standing` finds the last line standing per key;
`merge` folds a new observation into the line that stands (rule 3: tracked over inferred over
declared, the declared role always); `reconcile` applies it to a stream of drafts before they are
appended.

Two small tables ship with the package under `logbook/tables/`: `airports.csv` (OurAirports, public
domain: IATA, ICAO, name, latitude, longitude and an IANA zone, regenerated by
`scripts/make_airports.py`) and `airlines.csv` (IATA and ICAO designators). A file named by
`--airports` or `LOGBOOK_AIRPORTS` adds to or overrides the airports. Nothing here touches the
network.
"""

